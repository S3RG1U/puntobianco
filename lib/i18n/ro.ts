// Romanian adds "de" from 20 upwards: 1 zi, 19 zile, 20 de zile, 101 zile.
const quantity = (total: number, one: string, other: string) => {
  if (total === 1) return `1 ${one}`;
  const rest = total % 100;
  return `${total} ${total === 0 || (rest >= 1 && rest <= 19) ? "" : "de "}${other}`;
};

